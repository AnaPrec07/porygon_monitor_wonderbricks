"""Compile config/download_monitor/* into dm_common/config_data.py.

Pipelines cannot reliably read repo files at run time, so the YAML and CSV in
config/download_monitor/ are the source of truth and this module bakes them into
a Python module the pipelines import. A test fails when config_data.py is stale:

    uv run python src/download_monitor/dm_common/build_config.py
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
CONFIG_DIR = ROOT / "config" / "download_monitor"
OUT = HERE / "config_data.py"

sys.path.insert(0, str(HERE.parent))
from dm_common.classify import cidr_bounds  # noqa: E402


def load_config() -> dict:
    def y(name: str) -> dict:
        return yaml.safe_load((CONFIG_DIR / name).read_text(encoding="utf-8"))

    with (CONFIG_DIR / "supported_ip_ranges.csv").open(newline="", encoding="utf-8") as f:
        ranges = []
        for row in csv.DictReader(f):
            lo, hi = cidr_bounds(row["cidr"])
            ranges.append({**{k: v.strip() for k, v in row.items()}, "start_int": lo, "end_int": hi})
    return {
        "actions": y("download_actions.yml"),
        "channels": y("client_channels.yml"),
        "thresholds": y("thresholds.yml"),
        "export": y("export_columns.yml"),
        "ip_ranges": ranges,
    }


def render(cfg: dict) -> str:
    body = json.dumps(cfg, indent=2, sort_keys=True)
    return (
        '"""GENERATED by dm_common/build_config.py from config/download_monitor/. Do not edit."""\n\n'
        "import json\n\n"
        f"CONFIG = json.loads(r'''{body}''')\n"
    )


if __name__ == "__main__":
    OUT.write_text(render(load_config()), encoding="utf-8")
    print(f"wrote {OUT}")
